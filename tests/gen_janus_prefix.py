#!/usr/bin/env python3
"""Regenerate the tiny Janus oracle using vectorized PyTorch, CPU FP32.

The graph follows ataeff/janus4's janus_gpt_v4_lowrank.py at revision
8c87c65c062ad535d12d562f1693fadac05c086c. Echo explicitly multiplies back
through Wj, independently checking the native norm-squared identity.
Normal C tests consume the frozen header and need no Python or model download.
"""
from pathlib import Path
import math
import torch
import torch.nn.functional as F

torch.set_num_threads(1)
E,H,D,B,M,T,R,V=32,2,16,3,64,16,4,37
specs=[];w={}
def add(name,shape,factor=0.125,kind=0):
    salt=len(specs)+1
    z=torch.arange(math.prod(shape),dtype=torch.int64)
    a=(((z*17+salt*29+(z//7)*3)%97)-48).float()/64*factor
    if kind==1:a=1+(torch.arange(B).float()+1)/64
    if kind==2:a=(3-torch.arange(B).float())/32
    if kind==3:a=torch.tensor([0.375])
    if kind==4:a=torch.tensor([0.1875])
    specs.append((name,shape,salt,factor,kind));w[name]=a.reshape(shape)

add('resid_lambdas',(B,),kind=1);add('x0_lambdas',(B,),kind=2)
add('smear_lambda',(1,),kind=3);add('backout_lambda',(1,),kind=4)
add('transformer.wte.weight',(V,E),0.5)
for l in range(B):
    p=f'transformer.h.{l}.'
    add(p+'attn.wr_a',(H,E,R),0.25);add(p+'attn.wr_b',(H,R,T),0.25)
    add(p+'attn.gate',(H,3),1.)
    for n in ['c_q','c_k','c_v','wvr','wj','c_proj']:add(p+'attn.'+n+'.weight',(E,E))
    add(p+'mlp.w_gate.weight',(M,E));add(p+'mlp.w_up.weight',(M,E));add(p+'mlp.w_down.weight',(E,M))
add('lm_head.weight',(V,E));add('smear_gate.weight',(1,24),0.25)

def run(ids,smear=.375,eps=torch.finfo(torch.float32).eps):
    n=len(ids);mask=torch.triu(torch.full((n,n),float('-inf')),diagonal=1)
    def norm(x):return F.rms_norm(x,(x.shape[-1],),eps=eps)
    x=norm(w['transformer.wte.weight'][ids]);old=x
    x=torch.cat([x[:1],x[1:]+smear*torch.sigmoid(F.linear(x[1:,:24],w['smear_gate.weight']))*old[:-1]])
    x0=x.clone()
    f=1/(100000**(torch.arange(0,D,2).float()/D));angles=torch.outer(torch.arange(n).float(),f)
    c=angles.cos()[None,:,:];s=angles.sin()[None,:,:]
    def rot(a):
        a,b=a[...,:D//2],a[...,D//2:]
        return torch.cat([a*c+b*s,-a*s+b*c],-1)
    for l in range(B):
        p=f'transformer.h.{l}.'
        x=w['resid_lambdas'][l]*x+w['x0_lambdas'][l]*x0;xn=norm(x)
        def proj(k):return F.linear(xn,w[p+'attn.'+k+'.weight'])
        q,k,v=[proj(a).reshape(n,H,D).transpose(0,1) for a in ('c_q','c_k','c_v')]
        q=norm(rot(q))*1.2;k=norm(rot(k))*1.2
        content=F.scaled_dot_product_attention(q,k,v,is_causal=True)
        mid=torch.einsum('te,her->hr',xn,w[p+'attn.wr_a'])
        scores=torch.einsum('hr,hrj->hj',mid,w[p+'attn.wr_b'][:,:,:n])/math.sqrt(D)
        vr=proj('wvr').reshape(n,H,D).transpose(0,1)
        rr=(scores[:,None,:]+mask).softmax(-1)@vr
        echo=proj('wj');back=echo@w[p+'attn.wj.weight']
        es=15*torch.tanh((xn*back).sum(-1)/math.sqrt(E)/15)
        ea=(es[:,None]*es[None,:]+mask).softmax(-1)
        ev=echo.reshape(n,H,D).transpose(0,1);eo=ea@ev
        g=w[p+'attn.gate'].softmax(-1)
        mixed=g[:,0,None,None]*content+g[:,1,None,None]*rr+g[:,2,None,None]*eo
        x=x+F.linear(mixed.transpose(0,1).reshape(n,E),w[p+'attn.c_proj.weight'])
        xn=norm(x)
        x=x+F.linear(F.silu(F.linear(xn,w[p+'mlp.w_gate.weight']))*F.linear(xn,w[p+'mlp.w_up.weight']),w[p+'mlp.w_down.weight'])
        if l==B//2:backout=x.clone()
    x=norm(x-w['backout_lambda']*backout)
    return 15*torch.tanh(F.linear(x,w['lm_head.weight'])[-1]/15)

ids=[1,8,3,11,5,2,20];other=[9,4,17,6,21]
goldens=[run(ids[:i]) for i in range(1,len(ids)+1)]+[run(other),run(ids,smear=-.25),run(ids,eps=.0078125)]
out=['/* Generated by tests/gen_janus_prefix.py; synthetic data only. */',
     'enum { JP_E=32, JP_H=2, JP_D=16, JP_B=3, JP_M=64, JP_T=16, JP_R=4, JP_V=37 };',
     'static const struct { const char *name; int nd; uint64_t shape[3]; int salt; float factor; int kind; } jp_spec[] = {']
for name,shape,salt,factor,kind in specs:
    out.append('    {"%s", %d, {%s}, %d, %.9ff, %d},'%(name,len(shape),','.join(map(str,shape)),salt,factor,kind))
out.append('};\nstatic const float jp_gold[10][JP_V] = {')
for row in goldens:out.append('    {'+', '.join(f'{float(v):.9e}f' for v in row)+'},')
out.append('};\n')
Path(__file__).with_name('janus_prefix_fixture.h').write_text('\n'.join(out))
print('Wrote 10 full-logit PyTorch fixtures,',len(specs),'synthetic tensors; torch',torch.__version__)
